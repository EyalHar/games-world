export function detectGender(name) {
  const n = (name || '').trim();
  if (FEMALE_NAMES.has(n)) return { gender: 'female', certain: true };
  if (MALE_NAMES.has(n))   return { gender: 'male',   certain: true };
  // שם לא מוכר או דו-מיני → שאל
  return { gender: 'unknown', certain: false };
}

export function tryAgain(name, gender) {
  if (gender === 'female') return `נסי שוב ${name}, את יכולה!`;
  return `נסה שוב ${name}, אתה יכול!`;
}

export function encourage(name, gender) {
  if (gender === 'female') return `יופי ${name}! ממשיכי כך!`;
  return `יופי ${name}! ממשיך כך!`;
}
